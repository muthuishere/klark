/** The agent kinds in the same order the Blazor hub tests them. */
export function slashCommandsFor(agent?: string | null): SlashCommand[] {
  const a = (agent ?? '').toLowerCase();
  if (a.includes('claude')) return L.claude;
  if (a.includes('devin')) return L.devin;
  if (a.includes('codex')) return L.codex;
  if (a.includes('agy') || a.includes('antigravity')) return L.agy;
  if (a.includes('gemini')) return L.gemini;
  if (a.includes('opencode')) return L.opencode;
  if (a.includes('cursor')) return L.cursor;
  if (a.includes('copilot')) return L.copilot;
  if (a.includes('grok')) return L.grok;
  return [];
}
