    /// <summary>The commands for an agent name as the pane reports it ("claude", "Devin", ...); empty for the rest.</summary>
    public static IReadOnlyList<SlashCommand> For(string? agent)
    {
        var a = (agent ?? "").ToLowerInvariant();
        if (a.Contains("claude")) return Claude;
        if (a.Contains("devin")) return Devin;
        if (a.Contains("codex")) return Codex;
        if (a.Contains("agy") || a.Contains("antigravity")) return Agy;
        if (a.Contains("gemini")) return Gemini;
        if (a.Contains("opencode")) return OpenCode;
        if (a.Contains("cursor")) return Cursor;
        if (a.Contains("copilot")) return Copilot;
        if (a.Contains("grok")) return Grok;
        return []; // Amp and anything unverified: no popup
    }
