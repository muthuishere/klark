#!/usr/bin/env bash
# Regenerate site/src/content/docs/reference/cli.md from the real klark binary.
# Usage: site/scripts/gen-cli.sh [path/to/klark]   (default: target/debug/klark, built if missing)
# Only help-printing invocations are run; nothing starts a server or the TUI.
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
klark="${1:-$root/target/debug/klark}"
if [ ! -x "$klark" ]; then
  (cd "$root" && cargo build --bin klark)
fi
out="$root/site/src/content/docs/reference/cli.md"

# "title|args": each entry is run as `klark <args>` and its output (stdout+stderr) captured.
cmds=(
  "klark --help|--help"
  "klark hub|hub --help"
  "klark msg|msg --help"
  "klark expose|expose --help"
  "klark offer|offer --help"
  "klark transcript|transcript --help"
  "klark session|session"
  "klark agent|agent"
  "klark pane|pane"
  "klark tab|tab"
  "klark workspace|workspace"
  "klark worktree|worktree"
  "klark notification|notification"
  "klark integration|integration"
  "klark machine|machine"
  "klark api|api"
  "klark config|config"
)

{
  echo "---"
  echo "title: CLI reference"
  echo "description: Every klark command, as printed by the binary's own help."
  echo "---"
  echo
  echo "Generated by \`site/scripts/gen-cli.sh\` from \`$("$klark" --version 2>&1 | head -1)\`."
  echo "Do not edit by hand: rebuild klark and run the script again."
  echo
  echo "Bare \`klark\` starts or attaches the TUI, and bare \`klark server\` runs the headless server,"
  echo "so neither is listed here. A command group run without a subcommand prints its usage."
  for entry in "${cmds[@]}"; do
    title="${entry%%|*}"
    args="${entry#*|}"
    echo
    echo "## \`$title\`"
    echo
    echo '```text'
    # shellcheck disable=SC2086
    "$klark" $args 2>&1 | sed -e 's/[[:space:]]*$//' || true
    echo '```'
  done
} > "$out"
echo "wrote $out"
